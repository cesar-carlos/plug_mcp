import type pg from "pg";
import type {
  IsolatedOperationCaseExecutor,
  OperationCase,
} from "../../../application/persona-v2/operation-cases.js";
import type { OperationPackage } from "../../../application/persona-v2/operation-training.js";
import { operationScalarSchema } from "../../../application/persona-v2/operation-training.js";
import type { SqlOperationCommand, TypedScalar } from "../../../domain/persona-v2/operation.js";
import { canonicalJson } from "../../../domain/persona-v2/catalog.js";

const types = {
  string: "text",
  integer: "bigint",
  decimal: "numeric",
  date: "timestamptz",
  uuid: "uuid",
  boolean: "boolean",
};
const q = (v: string): string => {
  if (!/^[a-z_][a-z0-9_]*$/.test(v)) throw new Error("Identificador inválido.");
  return `"${v}"`;
};
const stableValue = (raw: unknown, type: string): unknown => {
  if (raw === null || typeof raw === "boolean") return raw;
  if (type === "decimal") {
    if (typeof raw !== "string" && typeof raw !== "number") throw new Error("Decimal inválido.");
    const value = String(raw);
    return value.includes(".") ? value.replace(/0+$/, "").replace(/\.$/, "") : value;
  }
  if (raw instanceof Date) return raw.toISOString();
  if (typeof raw === "string" || typeof raw === "number") return String(raw);
  throw new Error("Valor não escalar.");
};
/** Only instantiated with a random database owned by the runner/test. Never accepts source credentials. */
export class PostgresOperationCaseExecutor implements IsolatedOperationCaseExecutor {
  constructor(private readonly pool: pg.Pool) {}
  async evaluate(
    pkg: OperationPackage,
    command: SqlOperationCommand,
    test: OperationCase,
  ): Promise<boolean> {
    if (pkg.dialect !== "postgres") throw new Error("Runner real deste dialeto indisponível.");
    const tables = pkg.training.tables;
    if (
      test.input.fixtures.length !== tables.length ||
      new Set(test.input.fixtures.map((f) => f.table)).size !== tables.length ||
      tables.some((t) => !test.input.fixtures.some((f) => f.table === t.name))
    )
      throw new Error("Fixtures incompletas.");
    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");
      await client.query("SET LOCAL statement_timeout = '15000ms'");
      for (const table of tables) {
        const fixture = test.input.fixtures.find((f) => f.table === table.name)!;
        if (
          fixture.generated.some(
            (c) => !table.columns.some((col) => col.name === c && col.type === "integer"),
          )
        )
          throw new Error("Identificador gerado inválido.");
        await client.query(
          `CREATE TABLE ${q(table.name)} (${table.columns.map((c) => `${q(c.name)} ${types[c.type]}${fixture.generated.includes(c.name) ? " GENERATED BY DEFAULT AS IDENTITY" : ""}`).join(", ")}, PRIMARY KEY (${table.identity.map(q).join(", ")}))`,
        );
        for (const row of fixture.rows) {
          const columns = Object.keys(row);
          if (!columns.length || columns.some((c) => !table.columns.some((col) => col.name === c)))
            throw new Error("Coluna de fixture inválida.");
          await client.query(
            `INSERT INTO ${q(table.name)} (${columns.map(q).join(", ")}) VALUES (${columns.map((_, i) => `$${i + 1}`).join(", ")})`,
            columns.map((c) => row[c]!.value),
          );
        }
      }
      const outputs = new Map<string, Record<string, TypedScalar>>();
      let affectedRows = 0,
        conditionFailed = false;
      for (const step of command.steps) {
        const values: unknown[] = [];
        const sql = step.sql.replace(/:([a-z_][a-z0-9_]*)/g, (_, name: string) => {
          const p = step.params[name];
          if (!p) throw new Error("Binding ausente.");
          const scalar = p.kind === "value" ? p.scalar : outputs.get(p.stepId)?.[p.output];
          if (!scalar) throw new Error("Saída ausente.");
          values.push(scalar.value);
          return `$${values.length}`;
        });
        const result = await client.query<Record<string, unknown>>(sql, values);
        const count = step.effect === "select" ? result.rows.length : result.rowCount;
        const limit = step.effect === "select" ? step.expectedRows : step.affectedRows;
        if (count === null || !limit || count < limit.min || count > limit.max) {
          conditionFailed = true;
          break;
        }
        if (step.effect !== "select") affectedRows += count;
        if (affectedRows > command.maxAffectedRows) {
          conditionFailed = true;
          break;
        }
        const out: Record<string, TypedScalar> = {};
        for (const [key, type] of Object.entries(step.outputs)) {
          if (result.rows.length !== 1) {
            conditionFailed = true;
            break;
          }
          const raw = result.rows[0]![key];
          out[key] = operationScalarSchema.parse({
            type,
            value: raw instanceof Date ? raw.toISOString() : raw,
          });
        }
        if (conditionFailed) break;
        outputs.set(step.id, out);
      }
      if ("error" in test.expected) return conditionFailed;
      if (
        conditionFailed ||
        test.expected.affectedRows !== affectedRows ||
        test.expected.tables.length !== tables.length ||
        new Set(test.expected.tables.map((t) => t.table)).size !== tables.length
      )
        return false;
      for (const table of tables) {
        const expected = test.expected.tables.find((t) => t.table === table.name);
        if (!expected) return false;
        const actual = await client.query<Record<string, unknown>>(
          `SELECT * FROM ${q(table.name)} ORDER BY ${table.identity.map(q).join(", ")}`,
        );
        const normalize = (rows: readonly Record<string, unknown>[]) =>
          rows.map((row) =>
            Object.fromEntries(
              table.columns.map((c) => [c.name, stableValue(row[c.name], c.type)]),
            ),
          );
        const wanted = expected.rows.map((row) =>
          Object.fromEntries(Object.entries(row).map(([k, v]) => [k, v.value])),
        );
        if (canonicalJson(normalize(actual.rows)) !== canonicalJson(normalize(wanted)))
          return false;
      }
      return true;
    } finally {
      try {
        await client.query("ROLLBACK");
      } finally {
        client.release();
      }
    }
  }
}
