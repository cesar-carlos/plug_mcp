import { PersonaV2Error, type Source, type SqlEffect } from "./model.js";

const identifier = /^[a-z_][a-z0-9_]{0,99}$/;
const refuse = (): never => {
  throw new PersonaV2Error("INVALID_PLAN", "Recurso SQL fora da gramática física da operação.");
};

/** Qualify namespace and relation separately. */
export function quoteOperationTable(name: string, dialect: Source["dialect"]): string {
  const parts = name.split(".");
  if (name.length > 200 || parts.length > 2 || !parts.every((p) => identifier.test(p))) refuse();
  return parts
    .map((p) => (dialect === "mssql" || dialect === "sybase" ? `[${p}]` : `"${p}"`))
    .join(".");
}

/** Read only the exact canonical target generated by the operation compiler. */
export function operationTableFromSql(sql: string, effect: SqlEffect): string {
  const part = '(?:"[A-Za-z_][A-Za-z0-9_]{0,99}"|\\[[a-z_][a-z0-9_]{0,99}\\])';
  const target = `(${part}(?:\\s*\\.\\s*${part})?)`;
  const prefix =
    effect === "select"
      ? "^SELECT [\\s\\S]+? FROM "
      : effect === "insert"
        ? "^INSERT INTO "
        : effect === "update"
          ? "^UPDATE "
          : "^DELETE FROM ";
  const match =
    new RegExp(prefix + target + "(?=\\s+(?:WHERE|SET|OUTPUT|VALUES|RETURNING)\\b|\\s*\\(|$)").exec(
      sql,
    ) ?? refuse();
  const result = match[1]!
    .replaceAll('"', "")
    .replaceAll("[", "")
    .replaceAll("]", "")
    .replace(/\s/g, "")
    .toLowerCase();
  if (!result.split(".").every((p) => identifier.test(p)) || result.length > 200) refuse();
  return result;
}
